def xy_to_rowcol(x, y, gt):
    """Convert map coordinates (x,y) to row/col indices."""
    originX, pixelWidth, _, originY, _, pixelHeight = gt
    col = int((x - originX) / pixelWidth)
    row = int((y - originY) / pixelHeight)
    return row, col

